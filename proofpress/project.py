def _lines(items):
    return [i for i in (items or []) if str(i).strip()]


def render_product(p):
    out = [GENERATED_MARK, "", f"# {p.get('name') or 'Product'}: product definition", ""]
    out.append(
        "This file is the only source of truth for anything an article says about the product. "
        "If a feature isn't listed under \"What exists\", treat it as not existing. When in doubt, leave it out or ask the owner."
    )
    out += ["", "## Identity", ""]
    out.append(f"- **Name:** {p.get('name', '')}")
    if p.get("one_liner"):
        out.append(f"- **What it is:** {p['one_liner']}")
    if p.get("category"):
        out.append(f"- **Type:** {p['category']}")
    if p.get("audience"):
        out.append(f"- **Who it's for:** {p['audience']}")
    links = [l for l in p.get("links") or [] if l.get("url")]
    if links:
        out.append("- **Official links (the only URLs to use for the product):**")
        for l in links:
            out.append(f"  - {l.get('label') or 'Link'}: {l['url']}")
    out.append(f"- **Pricing (say exactly this, nothing more):** {p.get('pricing') or 'Not provided. Never state a price.'}")
    out += ["", "## What exists", ""]
    feats = [f for f in p.get("features") or [] if (f.get("name") or "").strip()]
    if feats:
        for f in feats:
            tier = f" _({f['tier']})_" if f.get("tier") else ""
            line = f"- **{f['name']}**{tier}"
            if f.get("detail"):
                line += f": {f['detail']}"
            if f.get("notes"):
                line += f" Note: {f['notes']}"
            out.append(line)
    else:
        out.append("- (No features listed yet. Do not describe any product features until the owner adds them.)")
    out += ["", "## What does NOT exist (never claim or imply these)", ""]
    ne = _lines(p.get("not_exist"))
    out += [f"- {x}" for x in ne] if ne else ["- (Nothing listed. Be conservative: only claim what is listed above.)"]
    out.append("- Anything about user numbers, ratings, reviews, awards, press or \"trusted by\": not provided unless listed above. Don't state or imply any.")
    out += ["", "## How to talk about it", ""]
    if p.get("positioning"):
        out.append(p["positioning"])
        out.append("")
    if p.get("disclosure"):
        out.append(f"- Disclosure line for lists and comparisons: \"{p['disclosure']}\"")
    for r in _lines(p.get("phrasing_rules")):
        out.append(f"- {r}")
    out.append("- One product section and one CTA per article is enough. Say plainly when another tool or a spreadsheet fits a reader better.")
    if (p.get("extra_markdown") or "").strip():
        out += ["", "## More detail from the owner", "", p["extra_markdown"].strip()]
    return "\n".join(out) + "\n"


def render_voice(v, site):
    lang = site.get("language") or "en"
    out = [GENERATED_MARK, "", "# Audience and voice", ""]
    out.append(f"- **Output language:** {lang}" + (f" ({site.get('spelling')} spelling)" if lang.startswith("en") else ""))
    if v.get("audience"):
        out.append(f"- **Reader:** {v['audience']}")
    if v.get("tone"):
        out.append(f"- **Tone:** {v['tone']}")
    d = _lines(v.get("do"))
    if d:
        out += ["", "## Do", ""] + [f"- {x}" for x in d]
    dn = _lines(v.get("dont"))
    if dn:
        out += ["", "## Don't", ""] + [f"- {x}" for x in dn]
    if (v.get("example") or "").strip():
        out += ["", "## A paragraph in the right voice", "", v["example"].strip()]
    if len(out) <= 5:
        out += ["", "(No voice notes yet. Default: a knowledgeable, plain-spoken colleague; second person; contractions; short paragraphs; specific numbers.)"]
    return "\n".join(out) + "\n"


def render_factcheck(f):
    out = [GENERATED_MARK, "", "# Fact-check rules for this site", ""]
    if f.get("ymyl"):
        out.append(
            "This site covers **Your Money or Your Life** topics. Wrong information can cost a reader money or health, and search engines hold these pages to a higher standard. "
            "**If a claim in the topics below can't be verified today against an approved source, it doesn't go in the article.**"
        )
    else:
        out.append("This site isn't flagged as YMYL. Factual claims still need a source; claims in the topics below need an approved source checked during the run.")
    if (f.get("topics") or "").strip():
        out += ["", "## Claims that must be verified live", "", f["topics"].strip()]
    srcs = [s for s in f.get("sources") or [] if s.get("url") or s.get("name")]
    out += ["", "## Approved sources (fetch during the run, cite inline)", ""]
    if srcs:
        for s in srcs:
            scope = f" (for: {s['scope']})" if s.get("scope") else ""
            out.append(f"- {s.get('name') or s.get('url')}: {s.get('url', '')}{scope}")
    else:
        out.append("- Official government or regulator sites and the first-party page of whatever is being described. Secondary sources (news, blogs) can point you to the official page but are never the citation.")
    if (f.get("rules") or "").strip():
        out += ["", "## Extra rules from the owner", "", f["rules"].strip()]
    if (f.get("disclaimer") or "").strip():
        out += ["", "## Disclaimer to end affected articles with", "", f"*{f['disclaimer'].strip()}*"]
    return "\n".join(out) + "\n"


def write_context(r, settings):
    ctx = r / "context"
    ctx.mkdir(parents=True, exist_ok=True)
    jobs = [
        ("product.md", settings["product"], lambda: render_product(settings["product"])),
        ("voice.md", settings["voice"], lambda: render_voice(settings["voice"], settings["site"])),
        ("factcheck.md", settings["factcheck"], lambda: render_factcheck(settings["factcheck"])),
    ]
    for name, section, render in jobs:
        path = ctx / name
        if section.get("manual") and path.exists():
            continue
        path.write_text(render(), encoding="utf-8")


# ---------------------------------------------------------------- init + validate

BACKLOG_HEADER = "keyword,cluster,priority,intent_hint,status,slug,published_at,notes\n"


def init(project, name=None):
    r = root(project)
    created = []
    for d in ["content/articles", "content/drafts", "static/images", "static/downloads", "context", ".proofpress"]:
        (r / d).mkdir(parents=True, exist_ok=True)
    sf = r / SETTINGS_FILE
    if not sf.exists():
        s = copy.deepcopy(DEFAULT_SETTINGS)
        if name:
            s["site"]["name"] = name
            s["product"]["name"] = name
        save(r, s)
        created.append(str(sf))
    else:
        write_context(r, load(r))
    bl = r / "backlog.csv"
    if not bl.exists():
        bl.write_text(BACKLOG_HEADER, encoding="utf-8")
        created.append(str(bl))
    gi = r / ".gitignore"
    if not gi.exists():
        gi.write_text("public/\n.proofpress/\n.DS_Store\n", encoding="utf-8")
    return {"project": str(r), "created": created}


def validate(project):
    """Return {'errors': [...], 'warnings': [...], 'ready': {...}} for the whole project."""
    from . import backlog as bl

    r = require_project(project)
    s = load(r)
    errors, warnings = [], []
    site, prod, pub = s["site"], s["product"], s["publish"]

    if not site.get("name"):
        errors.append("site.name is empty (Settings > Site)")
    base = (site.get("base_url") or "").rstrip("/")
    placeholder = re.match(r"^https?://(www\.)?example\.(com|org)$", base or "")
    if pub["mode"] == "site" and (not base or placeholder):
        errors.append("site.base_url is empty or a placeholder; canonicals, sitemap and OG tags need the final https:// domain")
    elif base and not base.startswith("https://"):
        warnings.append("site.base_url should start with https://")

    if not prod.get("name"):
        errors.append("product.name is empty (Settings > Product)")
    if not [f for f in prod.get("features") or [] if (f.get("name") or "").strip()] and not prod.get("manual"):
        errors.append("product has no features; the writer can't describe the product without them")
    if not _lines(prod.get("not_exist")) and not prod.get("manual"):
        warnings.append("product 'does NOT exist' list is empty; listing common wrong assumptions prevents invented features")
    if not prod.get("pricing"):
        warnings.append("product pricing statement is empty; articles will be told never to state a price")
    if not s["cta"].get("buttons"):
        warnings.append("CTA has no buttons; articles will have no call-to-action link")

    if s["factcheck"].get("ymyl") and not s["factcheck"].get("sources"):
        warnings.append("site is marked YMYL but has no approved sources listed")

    try:
        rows = bl.read(r)
        todo = [x for x in rows if x["status"] == "todo"]
        if not rows:
            errors.append("backlog.csv is empty; add keywords (Settings > Keywords)")
        elif not todo:
            warnings.append("backlog has no 'todo' rows; nothing left to write")
        for msg in bl.check(rows):
            warnings.append(msg)
    except bl.BacklogError as e:
        errors.append(str(e))

    deploy_ready, missing = publish_readiness(s)
    if missing:
        warnings.append("publishing not configured yet: " + "; ".join(missing))

    return {
        "errors": errors,
        "warnings": warnings,
        "ready": {"write": not errors, "publish": deploy_ready and not errors},
        "publish_target": publish_label(s),
    }


def publish_label(s):
    pub = s["publish"]
    if pub["mode"] == "site":
        return f"static site -> {pub['site_provider']}"
    return f"existing site -> {pub['existing_target']}"


def publish_readiness(s):
    pub, missing = s["publish"], []
    if pub["mode"] == "site":
        prov = pub["site_provider"]
        if prov == "none":
            missing.append("no deploy provider chosen (build only)")
        elif prov == "s3":
            for k in ("bucket", "cloudfront_distribution_id"):
                if not pub["s3"].get(k):
                    missing.append(f"publish.s3.{k}")
        elif prov == "cloudflare" and not pub["cloudflare"].get("project_name"):
            missing.append("publish.cloudflare.project_name")
        elif prov == "netlify" and not pub["netlify"].get("site_id"):
            missing.append("publish.netlify.site_id")
        elif prov == "git" and not pub["git"].get("repo_path"):
            missing.append("publish.git.repo_path")
    else:
        t = pub["existing_target"]
        if t == "markdown-repo" and not pub["markdown_repo"].get("repo_path"):
            missing.append("publish.markdown_repo.repo_path")
        elif t == "wordpress":
            for k in ("url", "username"):
                if not pub["wordpress"].get(k):
                    missing.append(f"publish.wordpress.{k}")
        elif t == "webhook" and not pub["webhook"].get("url"):
            missing.append("publish.webhook.url")
    return (not missing), missing


def state(project):
    p = root(project) / ".proofpress/state.json"
    if p.exists():
        return json.loads(p.read_text(encoding="utf-8"))
    return {}


def save_state(project, data):
    p = root(project) / ".proofpress/state.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
