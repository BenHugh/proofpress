class ProjectError(Exception):
    pass


def deep_merge(base, override):
    out = copy.deepcopy(base)
    for k, v in (override or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def root(project):
    p = Path(str(project)).expanduser().resolve()
    return p


def require_project(project):
    r = root(project)
    if not (r / SETTINGS_FILE).exists():
        raise ProjectError(
            f"{r} is not a ProofPress project (no {SETTINGS_FILE}). Run: proofpress init {r}"
        )
    return r


def load(project):
    r = require_project(project)
    data = json.loads((r / SETTINGS_FILE).read_text(encoding="utf-8"))
    return deep_merge(DEFAULT_SETTINGS, data)


def save(project, settings, regenerate=True):
    r = root(project)
    merged = deep_merge(DEFAULT_SETTINGS, settings)
    (r / SETTINGS_FILE).write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    if regenerate:
        write_context(r, merged)
    return merged


def slugify(text):
    s = text.lower().strip()
    s = re.sub(r"['’]", "", s)
    s = re.sub(r"[^a-z0-9À-ɏ぀-ヿ一-鿿]+", "-", s)
    return s.strip("-")[:80] or "article"


